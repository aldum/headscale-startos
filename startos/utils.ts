export type TailnetNode = {
  id: number
  name: string
  addresses: string[]
  user: string
  connected: boolean
  expired: boolean
  lastSeen: string | null
  createdAt: string | null
}

function formatTimestamp(value: unknown): string | null {
  if (
    value &&
    typeof value === 'object' &&
    'seconds' in value &&
    typeof value.seconds === 'number' &&
    value.seconds > 0
  ) {
    return new Date(value.seconds * 1000)
      .toISOString()
      .slice(0, 16)
      .replace('T', ' ')
  }
  if (
    typeof value === 'string' &&
    value.length > 0 &&
    !value.startsWith('0001-01-01')
  ) {
    return value.slice(0, 16).replace('T', ' ')
  }
  return null
}

export function parseNodes(raw: unknown): TailnetNode[] {
  const list = Array.isArray(raw) ? raw : raw === null ? [] : [raw]
  return list.flatMap((entry) => {
    if (!entry || typeof entry !== 'object') return []
    const node = entry as Record<string, unknown>
    const id = Number(node.id ?? node.nodeId)
    if (!Number.isInteger(id)) return []
    const givenName = node.given_name ?? node.givenName
    const name =
      (typeof givenName === 'string' && givenName) ||
      (typeof node.name === 'string' && node.name) ||
      (typeof node.hostname === 'string' && node.hostname) ||
      `#${id}`
    const addresses = Array.isArray(node.ip_addresses)
      ? node.ip_addresses.filter((a): a is string => typeof a === 'string')
      : Array.isArray(node.ipAddresses)
        ? node.ipAddresses.filter((a): a is string => typeof a === 'string')
        : Array.isArray(node.ips)
          ? node.ips.filter((a): a is string => typeof a === 'string')
          : []
    const user =
      node.user && typeof node.user === 'object'
        ? String((node.user as Record<string, unknown>).name ?? '')
        : ''
    const expirySeconds = timestampSeconds(node.expiry)
    return [
      {
        id,
        name,
        addresses,
        user,
        connected: node.online === true || node.connected === true,
        expired:
          node.expired === true ||
          (expirySeconds !== null && expirySeconds * 1000 < Date.now()),
        lastSeen: formatTimestamp(node.last_seen ?? node.lastSeen),
        createdAt: formatTimestamp(
          node.created_at ?? node.createdAt ?? node.registeredAt,
        ),
      },
    ]
  })
}

function timestampSeconds(value: unknown): number | null {
  if (
    value &&
    typeof value === 'object' &&
    'seconds' in value &&
    typeof value.seconds === 'number'
  ) {
    return value.seconds
  }
  if (typeof value === 'string' && value.length > 0) {
    const parsed = Date.parse(value)
    return Number.isNaN(parsed) ? null : Math.floor(parsed / 1000)
  }
  return null
}

